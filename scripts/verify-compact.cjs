async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const report = {layouts: []};
  for (const viewport of [{width:1440,height:900},{width:1920,height:1080}]) {
    await page.setViewportSize(viewport);
    await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
    await page.evaluate(() => document.fonts.ready);
    await page.locator('.holiday-hero').screenshot({path:`output/compact-hero-${viewport.width}.png`});
    report.layouts.push({...viewport,...await page.evaluate(() => ({height:document.documentElement.scrollHeight,overflow:document.documentElement.scrollWidth>innerWidth,visibleProducts:document.querySelector('#panel-arrivals').children.length,heroImages:[...document.querySelectorAll('.holiday-hero img')].map(img=>({complete:img.complete,width:img.naturalWidth})),sections:document.querySelectorAll('main>section').length}))});
  }
  await page.getByRole('tab',{name:'Best sellers'}).click();
  report.tabs = await page.locator('#panel-bestsellers').isVisible() && await page.locator('#panel-arrivals').isHidden();
  await page.getByRole('tab',{name:'Best sellers'}).press('ArrowLeft');
  report.keyboardTabs = await page.locator('#panel-arrivals').isVisible();
  await page.locator('.home-holidays').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>[...document.querySelectorAll('.home-holidays .fade-in')].every(el=>el.classList.contains('is-visible')));
  await page.locator('.home-holidays').screenshot({path:'output/compact-holidays.png'});
  await page.locator('#global-reach').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('#global-reach').dataset.globeReady==='true');
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.world-map-panel')).opacity==='1');
  const globeBefore = await page.locator('#nuobo-globe-canvas').screenshot({path:'output/compact-globe-a.png'});
  await page.waitForTimeout(700);
  const globeAfter = await page.locator('#nuobo-globe-canvas').screenshot({path:'output/compact-globe-b.png'});
  const different = (a,b) => a.length!==b.length || a.some((value,i)=>value!==b[i]);
  report.globeAnimated = different(globeBefore,globeAfter);
  await page.getByRole('button',{name:'Pause globe',exact:true}).click();
  const stoppedA = await page.locator('#nuobo-globe-canvas').screenshot();
  await page.waitForTimeout(600);
  const stoppedB = await page.locator('#nuobo-globe-canvas').screenshot();
  report.globePause = !different(stoppedA,stoppedB);
  await page.locator('.world-wave-band').scrollIntoViewIfNeeded();
  await page.waitForTimeout(200);
  const waveBefore = await page.evaluate(()=>document.querySelector('#nuobo-wave-canvas').toDataURL());
  await page.waitForTimeout(400);
  report.waveIndependent = await page.evaluate(a=>document.querySelector('#nuobo-wave-canvas').toDataURL()!==a,waveBefore);
  await page.getByRole('button',{name:'Europe',exact:true}).click();
  await page.waitForTimeout(1100);
  report.regionSwitch = await page.getByRole('button',{name:'Europe',exact:true}).getAttribute('aria-pressed')==='true';
  await page.locator('.world-wave-band').scrollIntoViewIfNeeded();
  await page.waitForTimeout(200);
  const regionWave = await page.evaluate(()=>document.querySelector('#nuobo-wave-canvas').toDataURL());
  await page.waitForTimeout(500);
  report.waveAfterRegion = await page.evaluate(a=>document.querySelector('#nuobo-wave-canvas').toDataURL()!==a,regionWave);
  await page.getByRole('button',{name:'Pause wave',exact:true}).click();
  const waveStopped = await page.evaluate(()=>document.querySelector('#nuobo-wave-canvas').toDataURL());
  await page.waitForTimeout(300);
  report.wavePause = await page.evaluate(a=>document.querySelector('#nuobo-wave-canvas').toDataURL()===a,waveStopped);
  const beforeDrag = await page.locator('#nuobo-globe-canvas').screenshot();
  const bounds = await page.locator('#nuobo-globe-canvas').boundingBox();
  await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);
  await page.mouse.down();
  await page.mouse.move(bounds.x+bounds.width/2+100,bounds.y+bounds.height/2+15,{steps:8});
  await page.mouse.up();
  report.globeDrag = different(beforeDrag,await page.locator('#nuobo-globe-canvas').screenshot());
  await page.locator('#global-reach').screenshot({path:'output/compact-world.png'});
  await page.getByRole('button',{name:'Resume globe',exact:true}).click();
  await page.getByRole('button',{name:'Resume wave',exact:true}).click();
  report.performance = await page.evaluate(async()=>{
    const longTasks=[];
    const observer = new PerformanceObserver(list=>longTasks.push(...list.getEntries().map(e=>e.duration)));
    observer.observe({type:'longtask',buffered:false});
    const intervals=[];
    await new Promise(resolve=>{let previous=0;const start=performance.now();function tick(now){if(previous)intervals.push(now-previous);previous=now;if(now-start<1500)requestAnimationFrame(tick);else resolve();}requestAnimationFrame(tick);});
    observer.disconnect();intervals.sort((a,b)=>a-b);
    return {frames:intervals.length,p95FrameMs:Math.round(intervals[Math.floor(intervals.length*.95)]),longTasks:longTasks.length};
  });
  await page.getByRole('button',{name:'Nuobo in real life'}).click();
  report.videoDialog = await page.locator('#home-film-dialog').isVisible();
  await page.getByRole('button',{name:'Close product film'}).click();
  await page.waitForFunction(()=>!document.querySelector('#home-film-dialog').open && document.querySelector('#home-film-dialog video').paused);
  report.videoClosed = await page.evaluate(()=>!document.querySelector('#home-film-dialog').open && document.querySelector('#home-film-dialog video').paused);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('button',{name:'Resume globe',exact:true}).waitFor();
  await page.getByRole('button',{name:'Resume wave',exact:true}).waitFor();
  report.reducedMotion = await page.getByRole('button',{name:'Resume globe',exact:true}).isVisible() && await page.getByRole('button',{name:'Resume wave',exact:true}).isVisible();
  await page.emulateMedia({reducedMotion:'no-preference'});
  report.errors = errors;
  for (const [key,value] of Object.entries(report)) if(typeof value==='boolean'&&!value) throw new Error(key+' failed');
  if(errors.length) throw new Error(errors.join('; '));
  return report;
}
